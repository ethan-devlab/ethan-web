import { expect, test } from '@playwright/test'

test('contour controls keep manual navigation and one keyboard focus outline', async ({ page, browserName }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/en/')
  await page.locator('.home-photography-deferred').scrollIntoViewIfNeeded()
  const carousel = page.getByRole('region', { name: 'Photography', exact: true })
  const previous = carousel.getByRole('button', { name: 'Previous photo', exact: true })
  const next = carousel.getByRole('button', { name: 'Next photo', exact: true })
  await next.hover()
  await expect.poll(() => next.evaluate(element => getComputedStyle(element, '::before').clipPath)).toContain('50%')
  await previous.focus()
  await page.keyboard.press(browserName === 'webkit' ? 'Alt+Tab' : 'Tab')
  await expect(next).toBeFocused()
  expect(await next.evaluate(element => getComputedStyle(element, '::before').opacity)).toBe('0')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await next.evaluate(element => getComputedStyle(element, '::before').transitionDuration)).toBe('0s')
  await page.keyboard.press('Enter')
  await expect(carousel.locator('.hp-carousel__name')).toHaveText('Tasik Cermin 2')
  expect(await next.evaluate(element => element.getBoundingClientRect().width)).toBe(42)
})

test('stops automatic playback for reduced motion while keeping manual navigation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/en/')
  await page.locator('.home-photography-deferred').scrollIntoViewIfNeeded()
  const carousel = page.getByRole('region', { name: 'Photography', exact: true })
  const caption = carousel.locator('.hp-carousel__name')
  await expect(caption).toHaveText('Sunset Through Buildings')
  await page.mouse.move(1, 1)
  await page.waitForTimeout(6500)
  await expect(caption).toHaveText('Sunset Through Buildings')
  await expect(carousel.locator('img')).toHaveCount(14)
  await expect(carousel.locator('a')).toHaveCount(0)
  await carousel.getByRole('button', { name: 'Next photo', exact: true }).click()
  await expect(caption).toHaveText('Tasik Cermin 2')
  expect(await carousel.locator('.swiper-wrapper').evaluate(e => getComputedStyle(e).transitionDuration)).toBe('0s')
  await page.keyboard.press('ArrowRight')
  await expect(caption).toHaveText('Yuguang Island')
  await carousel.getByRole('button', { name: 'Previous photo', exact: true }).click()
  await expect(caption).toHaveText('Tasik Cermin 2')
})

test('resumes six-second playback only after hover and focus both leave', async ({ page }) => {
  test.setTimeout(45000)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/en/')
  await page.locator('.home-photography-deferred').scrollIntoViewIfNeeded()
  const carousel = page.getByRole('region', { name: 'Photography', exact: true })
  const caption = carousel.locator('.hp-carousel__name')
  await page.mouse.move(1, 1)
  await expect(caption).toHaveText('Sunset Through Buildings')
  await expect(caption).toHaveText('Tasik Cermin 2', { timeout: 8000 })
  await carousel.hover()
  await carousel.focus()
  await page.waitForTimeout(6500)
  await expect(caption).toHaveText('Tasik Cermin 2')
  await page.mouse.move(1, 1)
  await page.waitForTimeout(6500)
  await expect(caption).toHaveText('Tasik Cermin 2')
  await page.getByRole('link', { name: 'Ethan Chan 曾嘉誠', exact: true }).focus()
  await expect(caption).toHaveText('Yuguang Island', { timeout: 8000 })
})
